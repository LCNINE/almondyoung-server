/**
 * 「이 제출은 직전 제출과 같은가」의 판정 — 발급 다이얼로그의 멱등성 키 재사용 기준이다.
 *
 * 서버의 발급 키는 `${submit_id}:${n}` (n = 1..quantity) 이고 유니크는
 * `(promotion_id, customer_id, issue_key)` 삼중이다. 그래서 **대상 집합과 수량이 같으면**
 * 같은 `submit_id` 를 다시 보내는 것이 정확히 「같은 제출의 재도착」이 되어 멱등하다.
 *
 * 왜 이 함수가 필요한가 — 이전 두 동작이 각각 반쪽이었다:
 *
 * 1. **키를 계속 들고 있으면**: [alice,bob] 을 제출했다가 alice 만 남기고 수량을 3 으로
 *    바꿔 재조회해도 옛 키가 남아, 겹치는 `n` 이 서버에서 duplicate 로 떨어져 **요청한
 *    장수보다 적게** 발급된다. 화면엔 아무 경고도 안 뜬다.
 * 2. **조회할 때마다 버리면**(직전 동작): 발급이 타임아웃 났을 때 관리자가 「조회」부터
 *    다시 누르면 새 키가 만들어져 **또 발급된다** — 이중 발급이다.
 *
 * 지문을 비교하면 둘 다 사라진다: 대상·수량이 그대로면 키를 재사용해 멱등하고, 실제로
 * 바뀌었으면 새 키를 만들어 전량 발급한다.
 *
 * 이 판정을 `.tsx` 안 클로저로 두지 않는 이유: admin-web 의 jest transform 은 `^.+\.(t|j)s$`
 * 라 `.tsx` 안의 로직은 **테스트가 실행조차 되지 않는다**(`skip-reason-labels.ts` 와 같은 이유).
 */

/**
 * 대상 집합과 수량으로 지문 문자열을 만든다.
 *
 * - **순서 무관**: 발급 키가 고객마다 독립이라 조회 순서는 제출을 바꾸지 않는다. 정렬한다.
 * - **중복 제거**: 같은 회원을 두 줄로 적어도 해석 결과는 한 명이다.
 * - **구분자 안전**: 각 id 의 길이를 앞에 붙여 `["a,b"]` 와 `["a","b"]` 가 절대 같은
 *   문자열이 되지 않게 한다. 단순 `join(',')` 은 그 둘을 구별하지 못하고, 그 충돌은 곧
 *   「대상이 바뀌었는데 옛 키를 재사용」 = 과소 발급이다.
 */
export function issueFingerprint(customerIds: string[], quantity: number): string {
  const unique = [...new Set(customerIds)].sort();
  const targets = unique.map((id) => `${id.length}:${id}`).join('|');
  return `q${quantity}|n${unique.length}|${targets}`;
}
